# SECTION 4: LLM-POWERED ENTITY & RELATIONSHIP EXTRACTOR
# ============================================================================

def parse_graph_elements_via_llm(document_content: str, document_name: str, model_name: str = "llama3.2") -> Tuple[List[GraphNode], List[GraphEdge]]:
    """Invokes LLM to construct nodes and relationships from raw text."""
    
    # Structural extraction prompt formatting
    extraction_prompt = f"""You are a structural parser. Extract core entities and relations from the text.
    
    Format your output strictly as a JSON object:
    {{
      "nodes": [
        {{"name": "Entity Name", "type": "PERSON/ORGANIZATION/CONCEPT/TECHNOLOGY/EVENT", "summary": "Brief explanation"}}
      ],
      "edges": [
        {{"source": "Source Name", "target": "Target Name", "type": "RELATIONSHIP_TYPE", "context": "How they connect"}}
      ]
    }}
    
    Text to analyze:
    {document_content}
    """
    
    try:
        # Chat completion via local inference engine
        completion = inference_client.chat(
            model=model_name,
            messages=[{"role": "user", "content": extraction_prompt}],
            format="json"
        )
        
        # Parse output JSON payload
        parsed_data = json.loads(completion['message']['content'])
        
        node_list = []
        for nd in parsed_data.get('nodes', []):
            # Generate stable md5 hash as node_id
            unique_hash = hashlib.md5(f"{nd['name']}_{document_name}".encode()).hexdigest()[:12]
            node_list.append(GraphNode(
                node_id=unique_hash,
                display_name=nd['name'],
                category=nd['type'],
                summary=nd['summary'],
                origin_document=document_name,
                text_snippet=document_content[:250] + "..."
            ))
            
        edge_list = []
        for eg in parsed_data.get('edges', []):
            edge_list.append(GraphEdge(
                source_node=eg['source'],
                target_node=eg['target'],
                edge_type=eg['type'],
                context=eg['context'],
                origin_document=document_name
            ))
            
        return node_list, edge_list
        
    except Exception as exc:
        st.warning(f"Error extracting structural elements: {exc}")
        return [], []


