EXTRACTION_PROMPT = """You are a knowledge-graph extraction engine. Extract the important entities and the relationships between them from the text.

Return ONLY a JSON object with this exact shape:
{{
  "nodes": [
    {{"name": "Entity Name", "type": "PERSON | ORGANIZATION | CONCEPT | TECHNOLOGY | EVENT | LOCATION | PRODUCT", "summary": "One sentence describing the entity, based on the text"}}
  ],
  "edges": [
    {{"source": "Entity Name", "target": "Entity Name", "type": "RELATIONSHIP_TYPE", "context": "Short phrase from the text explaining the link"}}
  ]
}}

Rules:
- Every node must have name, type and summary.
- Every edge's source and target must exactly match a node name.
- Use UPPER_SNAKE_CASE relationship types such as FOUNDED, WORKS_FOR, DEVELOPED, INVESTED_IN, LOCATED_IN.
- Only include facts stated in the text.

Text to analyze:
\"\"\"
{document}
\"\"\"
"""


def build_graph_elements(
    parsed_data: Any, document_content: str, document_name: str
) -> Tuple[List[GraphNode], List[GraphEdge]]:
    """Validate the LLM's JSON payload and convert it into nodes and edges.

    Malformed items are skipped instead of failing the whole document.
    """
    if not isinstance(parsed_data, dict):
        raise ExtractionError("The model did not return a JSON object.")

    nodes: Dict[str, GraphNode] = {}
    raw_nodes = parsed_data.get("nodes") or parsed_data.get("entities") or []
    for item in raw_nodes if isinstance(raw_nodes, list) else []:
        if isinstance(item, str):
            item = {"name": item}
        if not isinstance(item, dict):
            continue
        name = clean_str(item.get("name") or item.get("id") or item.get("entity"))
        if not name or not normalize_text(name):
            continue
        node_id = make_node_id(name)
        if node_id in nodes:
            continue
        category = normalize_label(item.get("type") or item.get("category") or item.get("label"), "CONCEPT")
        if category not in ALLOWED_NODE_TYPES:
            category = "CONCEPT"
        nodes[node_id] = GraphNode(
            node_id=node_id,
            display_name=name,
            category=category,
            summary=clean_str(item.get("summary") or item.get("description")),
            origin_document=document_name,
            text_snippet=find_snippet(document_content, name),
        )

    edges: Dict[Tuple[str, str, str], GraphEdge] = {}
    raw_edges = parsed_data.get("edges") or parsed_data.get("relationships") or parsed_data.get("relations") or []
    for item in raw_edges if isinstance(raw_edges, list) else []:
        if not isinstance(item, dict):
            continue
        source = clean_str(item.get("source") or item.get("from") or item.get("head"))
        target = clean_str(item.get("target") or item.get("to") or item.get("tail"))
        if not source or not target or not normalize_text(source) or not normalize_text(target):
            continue
        source_id, target_id = make_node_id(source), make_node_id(target)
        if source_id == target_id:
            continue
        # Prefer the canonical node spelling when the edge differs only in case/punctuation
        source = nodes[source_id].display_name if source_id in nodes else source
        target = nodes[target_id].display_name if target_id in nodes else target
        edge_type = normalize_label(item.get("type") or item.get("relation") or item.get("label"), "RELATED_TO")
        key = (source_id, target_id, edge_type)
        if key in edges:
            continue
        edges[key] = GraphEdge(
            source_node=source,
            target_node=target,
            edge_type=edge_type,
            context=clean_str(item.get("context") or item.get("description")),
            origin_document=document_name,
        )

    return list(nodes.values()), list(edges.values())


def parse_graph_elements_via_llm(
    document_content: str, document_name: str, model_name: str = DEFAULT_MODEL
) -> Tuple[List[GraphNode], List[GraphEdge]]:
    """Invoke the LLM to construct nodes and relationships from raw text.

    Raises ExtractionError with a readable message when extraction fails.
    """
    try:
        completion = inference_client.chat(
            model=model_name,
            messages=[{"role": "user", "content": EXTRACTION_PROMPT.format(document=document_content.strip())}],
            format="json",
            options={"temperature": 0},
        )
    except Exception as exc:
        raise ExtractionError(
            f"Could not reach Ollama at {OLLAMA_ENDPOINT} with model '{model_name}': {exc}"
        ) from exc

    raw = completion["message"]["content"]
    try:
        parsed = json.loads(raw)
    except (TypeError, json.JSONDecodeError) as exc:
        raise ExtractionError(f"The model returned invalid JSON: {exc}") from exc

    return build_graph_elements(parsed, document_content, document_name)


