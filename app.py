class Neo4jGraphStore:
    """Manages all read, write, and traversal operations for the Graph Database."""

    def __init__(self, connection_url: str, auth_user: str, auth_pass: str):
        self.db_driver = GraphDatabase.driver(connection_url, auth=(auth_user, auth_pass))
        self.db_driver.verify_connectivity()

    def __enter__(self) -> "Neo4jGraphStore":
        return self

    def __exit__(self, *exc_info) -> None:
        self.shutdown()

    def shutdown(self):
        """Close connection driver."""
        self.db_driver.close()

    def ensure_schema(self):
        """Create the uniqueness constraint used for MERGE lookups."""
        with self.db_driver.session() as db_session:
            db_session.run(
                "CREATE CONSTRAINT graphnode_id IF NOT EXISTS "
                "FOR (n:GraphNode) REQUIRE n.id IS UNIQUE"
            )

    def reset_database(self):
        """Removes all entities and links from the active graph."""
        with self.db_driver.session() as db_session:
            db_session.run("MATCH (n) DETACH DELETE n")

    def graph_size(self) -> Tuple[int, int]:
        """Return (node count, relationship count)."""
        with self.db_driver.session() as db_session:
            nodes = db_session.run("MATCH (n) RETURN count(n) AS cnt").single()["cnt"]
            edges = db_session.run("MATCH ()-[r]->() RETURN count(r) AS cnt").single()["cnt"]
        return nodes, edges

    # ---- Writes -------------------------------------------------------------

    @staticmethod
    def _write_node(tx, node: GraphNode):
        tx.run(
            """
            MERGE (e:GraphNode {id: $node_id})
            ON CREATE SET e.name = $display_name,
                          e.key = $key,
                          e.category = $category,
                          e.summary = $summary,
                          e.summary_key = $summary_key,
                          e.documents = [],
                          e.snippets = []
            ON MATCH SET e.summary_key = CASE WHEN coalesce(e.summary, '') = '' THEN $summary_key ELSE e.summary_key END,
                         e.summary = CASE WHEN coalesce(e.summary, '') = '' THEN $summary ELSE e.summary END,
                         e.category = CASE WHEN coalesce(e.category, 'CONCEPT') = 'CONCEPT'
                                           THEN $category ELSE e.category END
            WITH e
            WHERE NOT $origin_document IN e.documents
            SET e.documents = e.documents + $origin_document,
                e.snippets = e.snippets + $text_snippet,
                e.snippet_key = coalesce(e.snippet_key, '') + ' ' + $snippet_key
            """,
            node_id=node.node_id,
            key=normalize_text(node.display_name),
            display_name=node.display_name,
            category=node.category,
            summary=node.summary,
            summary_key=normalize_text(node.summary),
            snippet_key=normalize_text(node.text_snippet),
            origin_document=node.origin_document,
            text_snippet=node.text_snippet,
        )

    @staticmethod
    def _write_edge(tx, edge: GraphEdge, source_snippet: str, target_snippet: str):
        # Endpoints are matched by id; any endpoint the LLM forgot to list as a
        # node is created so the relationship is never silently dropped.
        tx.run(
            """
            MERGE (x:GraphNode {id: $source_id})
            ON CREATE SET x.name = $source, x.key = $source_key, x.category = 'CONCEPT', x.summary = '',
                          x.documents = [$origin_document], x.snippets = [$source_snippet],
                          x.snippet_key = $source_snippet_key
            MERGE (y:GraphNode {id: $target_id})
            ON CREATE SET y.name = $target, y.key = $target_key, y.category = 'CONCEPT', y.summary = '',
                          y.documents = [$origin_document], y.snippets = [$target_snippet],
                          y.snippet_key = $target_snippet_key
            MERGE (x)-[r:LINKED_TO {type: $edge_type}]->(y)
            ON CREATE SET r.context = $context, r.documents = [$origin_document]
            ON MATCH SET r.documents = CASE WHEN $origin_document IN r.documents
                                            THEN r.documents ELSE r.documents + $origin_document END
            """,
            source_id=make_node_id(edge.source_node),
            target_id=make_node_id(edge.target_node),
            source=edge.source_node,
            target=edge.target_node,
            source_key=normalize_text(edge.source_node),
            target_key=normalize_text(edge.target_node),
            source_snippet=source_snippet,
            target_snippet=target_snippet,
            source_snippet_key=normalize_text(source_snippet),
            target_snippet_key=normalize_text(target_snippet),
            edge_type=edge.edge_type,
            context=edge.context,
            origin_document=edge.origin_document,
        )

    def ingest(self, nodes: List[GraphNode], edges: List[GraphEdge], document_content: str):
        """Write a document's nodes and edges in a single transaction."""
        def work(tx):
            for node in nodes:
                self._write_node(tx, node)
            for edge in edges:
                self._write_edge(
                    tx, edge,
                    find_snippet(document_content, edge.source_node),
                    find_snippet(document_content, edge.target_node),
                )

        with self.db_driver.session() as db_session:
            db_session.execute_write(work)

    # Single-item helpers kept for backwards compatibility
    def insert_node(self, node: GraphNode):
        with self.db_driver.session() as db_session:
            db_session.execute_write(self._write_node, node)

    def insert_edge(self, edge: GraphEdge):
        with self.db_driver.session() as db_session:
            db_session.execute_write(self._write_edge, edge, "", "")

    # ---- Reads --------------------------------------------------------------

    def find_entry_nodes(self, question: str, limit: int = MAX_ENTRY_NODES) -> List[Dict]:
        """Rank nodes by how well they match the question.

        A node scores highest when its full name appears in the question as whole
        words, then by how many question keywords start a word in its name or
        summary. Matching is case- and punctuation-insensitive. Nodes matched only
        through their summary or source text are a fallback when nothing matches by name.
        """
        terms = [f" {t}" for t in extract_search_terms(question)]
        padded_question = f" {normalize_text(question)} "
        with self.db_driver.session() as db_session:
            cursor = db_session.run(
                """
                MATCH (n:GraphNode)
                WITH n,
                     ' ' + coalesce(n.key, toLower(n.name)) + ' ' AS key,
                     ' ' + coalesce(n.summary_key, toLower(coalesce(n.summary, ''))) + ' ' AS summary,
                     ' ' + coalesce(n.snippet_key, '') + ' ' AS evidence
                WITH n,
                     (trim(key) <> '' AND $question CONTAINS key) AS named,
                     size([t IN $terms WHERE key CONTAINS t]) AS name_hits,
                     size([t IN $terms WHERE summary CONTAINS t]) AS summary_hits,
                     size([t IN $terms WHERE evidence CONTAINS t]) AS evidence_hits
                WHERE named OR name_hits > 0 OR summary_hits > 0 OR evidence_hits > 0
                RETURN n.id AS id,
                       n.name AS name,
                       n.summary AS summary,
                       n.category AS type,
                       n.documents AS documents,
                       n.snippets AS snippets,
                       (named OR name_hits > 0) AS name_match,
                       (CASE WHEN named THEN 10 ELSE 0 END) + name_hits * 3 + summary_hits * 2 + evidence_hits AS relevance
                ORDER BY name_match DESC, relevance DESC, size(name) DESC
                LIMIT $fetch_limit
                """,
                question=padded_question,
                terms=terms,
                fetch_limit=limit * 3,
            )
            matches = [dict(record) for record in cursor]
        # When some nodes match by name, weaker summary/source-text matches are dropped;
        # multi-hop expansion from the named nodes brings in related entities anyway.
        if any(m["name_match"] for m in matches):
            matches = [m for m in matches if m["name_match"]]
        return matches[:limit]

    def query_nodes_by_text(self, text_query: str) -> List[Dict]:
        """Backwards-compatible alias for keyword-based node lookup."""
        return self.find_entry_nodes(text_query, limit=12)

    def fetch_hops_context(self, node_id: str, depth: int = DEFAULT_HOP_DEPTH, limit: int = 25) -> List[Dict]:
        """Traverse up to `depth` hops from a node and return each neighbour once,
        along with the shortest path that reaches it."""
        # Variable-length bounds cannot be parameters; only a clamped integer is interpolated.
        depth = max(1, min(int(depth), 5))
        with self.db_driver.session() as db_session:
            cursor = db_session.run(
                f"""
                MATCH path = (root:GraphNode {{id: $node_id}})-[*1..{depth}]-(neighbor:GraphNode)
                WHERE neighbor.id <> $node_id
                WITH neighbor, path
                ORDER BY length(path) ASC
                WITH neighbor, collect(path)[0] AS p
                RETURN neighbor.id AS id,
                       neighbor.name AS name,
                       neighbor.summary AS summary,
                       neighbor.category AS type,
                       neighbor.documents AS documents,
                       neighbor.snippets AS snippets,
                       length(p) AS hops,
                       [x IN nodes(p) | x.name] AS path_names,
                       [r IN relationships(p) |
                           startNode(r).name + ' -[' + r.type + ']-> ' + endNode(r).name +
                           coalesce(': ' + r.context, '')] AS relations
                ORDER BY hops ASC, name ASC
                LIMIT $limit
                """,
                node_id=node_id,
                limit=limit,
            )
            return [dict(record) for record in cursor]


