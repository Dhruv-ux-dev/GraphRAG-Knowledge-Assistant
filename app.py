@dataclass
class GraphNode:
    """Represents a node (entity) in the Neo4j knowledge graph."""
    node_id: str            # Stable identifier derived from the normalized entity name
    display_name: str       # Name of the entity
    category: str           # Entity type/label (e.g., PERSON)
    summary: str            # Short explanation of the entity
    origin_document: str    # Source document name
    text_snippet: str       # Sentence(s) of the source text that mention the entity


@dataclass
class GraphEdge:
    """Represents a directed relationship between two nodes."""
    source_node: str        # Origin node name
    target_node: str        # Destination node name
    edge_type: str          # Type of link (e.g., WORKS_FOR)
    context: str            # Text explaining the relationship connection
    origin_document: str    # Source document name


@dataclass
class SourceAttribution:
    """Represents verifiable source provenance details for claims."""
    claim_text: str         # Citation marker and entity it refers to
    doc_source: str         # Source document name(s)
    reference_text: str     # Raw text segment(s) supporting the claim
    score: float            # Graph proximity to the question (1.0 = directly matched)
    path_trace: List[str]   # Traversal path inside the graph


@dataclass
class AttributedAnswer:
    """Consolidated response object containing the answer and source traces."""
    content: str                                   # Final text generated by the LLM
    sources: List[SourceAttribution]               # Validated citations list
    execution_steps: List[str]                     # Audit log of the retrieval path
    context_entries: List[Dict[str, Any]] = field(default_factory=list)  # Numbered context sent to the LLM


# ============================================================================
# SECTION 3: TEXT NORMALIZATION HELPERS
# ============================================================================

def normalize_text(value: str) -> str:
    """Lowercase, replace punctuation with spaces and collapse whitespace."""
    return " ".join(re.sub(r"[^0-9a-z]+", " ", str(value).lower()).split())


def make_node_id(name: str) -> str:
    """Stable node id so the same entity merges across documents."""
    return hashlib.md5(normalize_text(name).encode("utf-8")).hexdigest()[:12]


def normalize_label(value: Any, default: str) -> str:
    """Convert free-form labels such as 'works for' into UPPER_SNAKE_CASE."""
    label = re.sub(r"[^0-9A-Za-z]+", "_", str(value or "")).strip("_").upper()
    return label or default


def clean_str(value: Any) -> str:
    """Return a trimmed string for any JSON scalar, or an empty string."""
    if value is None or isinstance(value, (dict, list)):
        return ""
    return " ".join(str(value).split())


def find_snippet(document: str, term: str, radius: int = SNIPPET_RADIUS) -> str:
    """Return the passage of the document that mentions the term, for attribution."""
    text = " ".join(document.split())
    if not text:
        return ""
    idx = text.lower().find(term.lower()) if term else -1
    if idx < 0:
        # Fall back to the first meaningful word of the term (e.g. a surname)
        for word in sorted(normalize_text(term).split(), key=len, reverse=True):
            if len(word) > 3:
                idx = text.lower().find(word)
                if idx >= 0:
                    break
    if idx < 0:
        return text[: radius * 2] + ("..." if len(text) > radius * 2 else "")

    start = max(0, idx - radius)
    end = min(len(text), idx + len(term) + radius)
    # Expand to sentence boundaries where possible
    sentence_start = text.rfind(". ", start, idx)
    if sentence_start != -1:
        start = sentence_start + 2
    sentence_end = text.find(". ", idx + len(term), end)
    if sentence_end != -1:
        end = sentence_end + 1
    snippet = text[start:end].strip()
    prefix = "..." if start > 0 else ""
    suffix = "..." if end < len(text) and not snippet.endswith(".") else ""
    return f"{prefix}{snippet}{suffix}"


def extract_search_terms(question: str) -> List[str]:
    """Turn a natural-language question into lowercase keyword search terms."""
    terms: List[str] = []
    for token in normalize_text(question).split():
        if len(token) < 3 or token in STOPWORDS:
            continue
        # Light plural stemming so 'backs' still matches 'backed' (terms match word prefixes)
        if len(token) > 4 and token.endswith("s") and not token.endswith("ss"):
            token = token[:-1]
        if token not in terms:
            terms.append(token)
    return terms


