                            try:
                                store.ensure_schema()
                                store.ingest(nodes, edges, document_payload)
                            except Exception as ex:
                                st.error(f"Failed to write to Neo4j: {ex}")
                            else:
                                st.success(f"Loaded {len(nodes)} entities and {len(edges)} relationships.")
                                if user_doc_name.strip() not in st.session_state.processed_docs:
                                    st.session_state.processed_docs.append(user_doc_name.strip())

                                with st.expander("Ingested entities", expanded=True):
                                    for en in nodes:
                                        st.write(f"🔹 **{en.display_name}** ({en.category}): {en.summary or '—'}")
