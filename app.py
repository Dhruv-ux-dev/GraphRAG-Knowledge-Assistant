def _pick_evidence(documents: Optional[Iterable[str]], snippets: Optional[Iterable[str]]) -> Tuple[str, str]:
    """Pair each source document with its snippet (the lists are stored in parallel)."""
    docs = list(documents or [])
    snips = list(snippets or [])
    pairs = [(d, snips[i] if i < len(snips) else "") for i, d in enumerate(docs) if d]
    doc_label = ", ".join(dict.fromkeys(d for d, _ in pairs)) or "Unknown document"
    with_text = [(d, s) for d, s in pairs if s]
    if len(with_text) > 1:
        evidence = "\n\n".join(f"[{d}] {s}" for d, s in with_text)
    else:
        evidence = with_text[0][1] if with_text else ""
    return doc_label, evidence


def collect_graph_context(
    question: str, graph_store: Neo4jGraphStore, depth: int = DEFAULT_HOP_DEPTH
) -> Tuple[List[Dict[str, Any]], List[str]]:
    """Find entry nodes for the question and expand them across the graph."""
    trace = [f"🔎 Searching the graph for: '{question}'"]
    terms = extract_search_terms(question)
    trace.append(f"🧩 Search terms: {', '.join(terms) if terms else '(none)'}")

    entry_nodes = graph_store.find_entry_nodes(question)
    if not entry_nodes:
        return [], trace
    trace.append(f"📊 Matched {len(entry_nodes)} starting node(s): {', '.join(n['name'] for n in entry_nodes)}")

    entries: Dict[str, Dict[str, Any]] = {}

    def add_entry(record: Dict[str, Any], hops: int, path: List[str], relations: List[str]):
        node_id = record["id"]
        existing = entries.get(node_id)
        if existing is None:
            doc_label, evidence = _pick_evidence(record.get("documents"), record.get("snippets"))
            entries[node_id] = {
                "id": node_id,
                "name": record["name"],
                "type": record.get("type") or "CONCEPT",
                "summary": record.get("summary") or "",
                "document": doc_label,
                "evidence": evidence,
                "hops": hops,
                "path": path,
                "relations": list(relations),
            }
        else:
            if hops < existing["hops"]:
                existing["hops"], existing["path"] = hops, path
            for rel in relations:
                if rel not in existing["relations"]:
                    existing["relations"].append(rel)

    for node in entry_nodes:
        add_entry(node, 0, [node["name"]], [])

    for node in entry_nodes:
        trace.append(f"🔗 Traversing up to {depth} hop(s) from: {node['name']}")
        neighbors = graph_store.fetch_hops_context(node["id"], depth=depth)
        if not neighbors:
            trace.append("  → No connected entities")
        for nb in neighbors:
            add_entry(nb, nb["hops"], nb.get("path_names") or [], nb.get("relations") or [])
            # Record direct relationships on the entry node as well
            if nb["hops"] == 1:
                for rel in nb.get("relations") or []:
                    if rel not in entries[node["id"]]["relations"]:
                        entries[node["id"]]["relations"].append(rel)
            trace.append(f"  → {nb['hops']} hop(s): {' ➔ '.join(nb.get('path_names') or [nb['name']])}")

    ordered = sorted(entries.values(), key=lambda e: (e["hops"], e["name"].lower()))[:MAX_CONTEXT_ENTRIES]
    return ordered, trace


def format_context(entries: List[Dict[str, Any]]) -> str:
    """Render numbered context entries for the answering prompt."""
    blocks = []
    for idx, entry in enumerate(entries, start=1):
        lines = [f"[{idx}] {entry['name']} ({entry['type']}) — {entry['summary'] or 'No summary.'}"]
        if entry["relations"]:
            lines.append("    Relationships: " + "; ".join(entry["relations"][:6]))
        if entry["evidence"]:
            evidence = " | ".join(part.strip() for part in entry["evidence"].split("\n\n") if part.strip())
            lines.append(f"    Source ({entry['document']}): {evidence[:600]}")
        blocks.append("\n".join(lines))
    return "\n".join(blocks)


ANSWER_PROMPT = """You answer questions using ONLY the knowledge-graph context below.

Rules:
- Cite the numbered context items that support each claim using [N] notation, e.g. [1] or [2][3].
- Only use citation numbers that appear in the context.
- If the context does not contain the answer, say so plainly instead of guessing.

CONTEXT:
{context}

QUESTION: {question}

Answer concisely with inline citations."""


def run_attributed_graph_rag(
    user_query: str,
    graph_store: Neo4jGraphStore,
    model_name: str = DEFAULT_MODEL,
    depth: int = DEFAULT_HOP_DEPTH,
) -> AttributedAnswer:
    """Execute multi-hop retrieval and return an answer backed by citations."""
    entries, trace_steps = collect_graph_context(user_query, graph_store, depth)

    if not entries:
        return AttributedAnswer(
            content=(
                "No entities in the knowledge graph match this question. "
                "Try naming a person, organization or product from your ingested documents."
            ),
            sources=[],
            execution_steps=trace_steps,
        )

    compiled_context = format_context(entries)
    trace_steps.append(f"📝 Compiled context from {len(entries)} graph node(s)")

    try:
        response = inference_client.chat(
            model=model_name,
            messages=[{"role": "user", "content": ANSWER_PROMPT.format(context=compiled_context, question=user_query)}],
            options={"temperature": 0.1},
        )
        answer_text = response["message"]["content"]
    except Exception as error:
        trace_steps.append("❌ Answer generation failed")
        return AttributedAnswer(
            content=f"Could not generate an answer with model '{model_name}': {error}",
            sources=[],
            execution_steps=trace_steps,
            context_entries=entries,
        )
    trace_steps.append(f"✅ Generated answer with {model_name}")

    # Check every inline citation against the numbered context
    attributions: List[SourceAttribution] = []
    cited_numbers = sorted({int(n) for n in re.findall(r"\[(\d+)\]", answer_text)})
    invalid = [n for n in cited_numbers if not 1 <= n <= len(entries)]
    for number in cited_numbers:
        if number in invalid:
            continue
        entry = entries[number - 1]
        attributions.append(SourceAttribution(
            claim_text=f"[{number}] {entry['name']}",
            doc_source=entry["document"],
            reference_text=entry["evidence"] or entry["summary"],
            score=round(1.0 / (1 + entry["hops"]), 2),
            path_trace=entry["path"] or [entry["name"]],
        ))

    trace_steps.append(f"🔒 Matched {len(attributions)} citation(s) to graph context")
    if invalid:
        trace_steps.append(f"⚠️ Ignored citation(s) not present in the context: {', '.join(f'[{n}]' for n in invalid)}")
    if not cited_numbers:
        trace_steps.append("⚠️ The model did not include any citations")

    return AttributedAnswer(
        content=answer_text,
        sources=attributions,
        execution_steps=trace_steps,
        context_entries=entries,
    )


