def open_store(db_uri: str, db_user: str, db_pass: str) -> Optional[Neo4jGraphStore]:
    """Connect to Neo4j, showing a readable error in the UI on failure."""
    try:
        return Neo4jGraphStore(db_uri, db_user, db_pass)
    except Exception as exc:
        st.error(f"Could not connect to Neo4j at {db_uri}: {exc}")
        st.info("Check that Neo4j is running and that the URI, username and password in the sidebar are correct.")
