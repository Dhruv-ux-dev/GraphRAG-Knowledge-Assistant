# SECTION 2: DATACLASSES FOR KNOWLEDGE REPRESENTATION
# ============================================================================

@dataclass
class GraphNode:
    """Represents a node (entity) in the Neo4j knowledge graph."""
    node_id: str            # Unique identifier for the node
    display_name: str       # Name of the entity
    category: str           # Entity type/label (e.g., PERSON)
    summary: str            # Short explanation of the entity
    origin_document: str    # Source document name
    text_snippet: str       # Original text snippet context


@dataclass
class GraphEdge:
    """Represents a directed relationship between two nodes."""
    source_node: str        # Origin node name
    target_node: str        # Destination node name
    edge_type: str          # Type of link (e.g., WORKS_FOR)
    context: str            # Text explaining the relationship connection
    origin_document: str    # Source document name


@dataclass
class SourceAttribution:
    """Represents verifiable source provenance details for claims."""
    claim_text: str         # Claim statement made by the agent
    doc_source: str         # Source document file name
    reference_text: str     # Raw text segment proving the claim
    score: float            # Relevance/confidence score
    path_trace: List[str]   # Traversal path inside the graph


@dataclass
class AttributedAnswer:
    """Consolidated response object containing the answer and source traces."""
    content: str            # Final text generated by LLM
    sources: List[SourceAttribution]    # Validated citations list
    execution_steps: List[str]          # Audit logs of retrieval path


